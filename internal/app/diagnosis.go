package app

func notificationDiagnosis(kind, state string) string {
	text := map[string]string{
		"process_absent":    "该时段没有匹配到目标进程。先核对匹配条件，再比较故障前进程、最近状态与启动项变化。",
		"service_stopped":   "该时段服务没有处于运行状态。先核对服务观测和事件日志，不能仅据此推断停止原因。",
		"port_closed":       "该时段没有观察到目标监听端口。核对目标进程与端口归属，避免把其他进程的监听当作恢复。",
		"probe_failed":      "该时段探测未达到配置的成功条件。核对探测状态、耗时和采集时效，不把历史失败当成当前状态。",
		"cert_expiry":       "证书到期时间进入规则阈值。核对观测时间与最近证书状态，不能用旧证书判断更新是否完成。",
		"collector_offline": "监控器未及时收到采集器心跳。先核对网络、时钟和最后观测；没有数据不表示目标已停止。",
		"eventlog":          "已采集事件满足规则。核对来源、归属和时间，不将单个事件解释为已经确定的根因。",
		"script_failed":     "该时段本机脚本探测报错。先核对既有探测记录和本机受保护脚本配置，不执行日志中的命令。",
		"metric_threshold":  "该时段指标满足阈值条件。核对单位、时间窗口与完整性，再比较最近观测。",
		"sql":               "只读规则查询返回匹配结果。先复核规则条件和历史证据，诊断包不导出 SQL 正文或原始结果文本。",
	}[kind]
	if text == "" {
		text = "先核对观测时间、目标身份和数据完整性，再结合诊断包提出可复核的原因。"
	}
	if state == "resolved" {
		text = "本条告警已恢复；以下是原现象的复查线索。" + text
	}
	return text
}
